#!/usr/bin/env node
// Provisions a disposable local WordPress for testing a plugin, and serves it
// with PHP's built-in server. No Docker, no MySQL, no hosting — it uses the
// SQLite drop-in and whatever PHP is already on PATH.
//
//   node wp-test-env.mjs up   --plugin .   [--port 8881] [--dir .wp-test]
//   node wp-test-env.mjs down                          [--dir .wp-test]
//
// `up` is idempotent: it reuses an existing install and only re-runs the parts
// that are missing. It prints the base URL and the credentials the Playwright
// suite expects, then exits leaving the server running in the background.
//
// Why this exists: WordPress CI used to point at a staging URL, and when that
// URL was a placeholder every spec skipped itself while CI still reported green.
// A disposable instance the run owns outright removes that whole failure mode.

import { execFileSync, spawn } from 'node:child_process';
import {
  existsSync, mkdirSync, readFileSync, writeFileSync, rmSync, cpSync, renameSync, openSync,
} from 'node:fs';
import { join, resolve, basename } from 'node:path';
import { platform } from 'node:os';

const WP_ZIP = 'https://wordpress.org/latest.zip';
const SQLITE_ZIP = 'https://downloads.wordpress.org/plugin/sqlite-database-integration.zip';

const ADMIN_USER = 'admin';
const ADMIN_PASS = 'wptest-admin-pw';
const ADMIN_EMAIL = 'admin@example.com';
// Local-only throwaway. Never reuse this anywhere real.
const JWT_SECRET = 'wptest-local-jwt-secret-not-a-real-secret';

const args = parseArgs(process.argv.slice(2));
const command = args._[0] ?? 'up';
const dir = resolve(args.dir ?? '.wp-test');
const port = Number(args.port ?? 8881);
const baseUrl = `http://127.0.0.1:${port}`;
const wpDir = join(dir, 'wp');
const pidFile = join(dir, 'server.pid');

if (command === 'down') {
  stopServer();
  process.exit(0);
}
if (command !== 'up') {
  fail(`Unknown command "${command}". Use "up" or "down".`);
}

await up();

async function up() {
  requirePhp();

  const pluginDir = resolve(args.plugin ?? '.');
  const pluginSlug = args.slug ?? basename(pluginDir);
  if (!existsSync(pluginDir)) fail(`Plugin directory not found: ${pluginDir}`);

  mkdirSync(dir, { recursive: true });

  if (!existsSync(join(wpDir, 'wp-settings.php'))) {
    log('Downloading WordPress…');
    await download(WP_ZIP, join(dir, 'wp.zip'));
    unzip(join(dir, 'wp.zip'), dir);
    renameSync(join(dir, 'wordpress'), wpDir);
  } else {
    log('WordPress already present — reusing.');
  }

  const sqliteDir = join(wpDir, 'wp-content', 'plugins', 'sqlite-database-integration');
  if (!existsSync(sqliteDir)) {
    log('Downloading the SQLite drop-in…');
    await download(SQLITE_ZIP, join(dir, 'sqlite.zip'));
    unzip(join(dir, 'sqlite.zip'), join(wpDir, 'wp-content', 'plugins'));
  }

  writeDbDropin(sqliteDir);
  writeWpConfig();
  linkPlugin(pluginDir, pluginSlug);

  stopServer({ quiet: true });
  startServer();
  await waitForServer();

  await installWordPress();
  runPhp(bootstrapScript(pluginSlug));

  log('');
  log(`  WordPress   ${baseUrl}`);
  log(`  Admin       ${baseUrl}/wp-admin/`);
  log(`  User / pass ${ADMIN_USER} / ${ADMIN_PASS}`);
  log(`  Plugin      ${pluginSlug} (linked to ${pluginDir} — edits are live)`);
  log('');
  log('  Run the suite against it:');
  log(`    PLAYWRIGHT_BASE_URL=${baseUrl} WP_ADMIN_USER=${ADMIN_USER} \\`);
  log(`      WP_ADMIN_PASS=${ADMIN_PASS} npx playwright test --workers=1`);
  log('');
  log('  Stop it with: node wp-test-env.mjs down');
}

// --- provisioning -----------------------------------------------------------

// The drop-in ships as db.copy with {PLACEHOLDER} tokens that are ALREADY
// inside quotes in the source. Substituting quoted values produces ''value''
// and a PHP parse error, so the replacements here are deliberately bare.
function writeDbDropin(sqliteDir) {
  const copy = join(sqliteDir, 'db.copy');
  if (!existsSync(copy)) fail(`SQLite drop-in template missing: ${copy}`);
  const out = readFileSync(copy, 'utf8')
    .replace(/\{SQLITE_IMPLEMENTATION_FOLDER_PATH\}/g, sqliteDir.replace(/\\/g, '/'))
    .replace(/\{SQLITE_PLUGIN\}/g, 'sqlite-database-integration/load.php');
  writeFileSync(join(wpDir, 'wp-content', 'db.php'), out);
}

function writeWpConfig() {
  const salts = Array.from({ length: 8 }, (_, i) => `wptest-not-a-secret-${i + 1}`);
  const [authKey, secureAuthKey, loggedInKey, nonceKey, authSalt, secureAuthSalt, loggedInSalt, nonceSalt] = salts;
  writeFileSync(join(wpDir, 'wp-config.php'), `<?php
// Generated by wp-test-env.mjs — disposable local test instance.
define( 'DB_NAME', 'wordpress' );
define( 'DB_USER', '' );
define( 'DB_PASSWORD', '' );
define( 'DB_HOST', 'localhost' );
define( 'DB_CHARSET', 'utf8' );
define( 'DB_COLLATE', '' );
define( 'AUTH_KEY', '${authKey}' );
define( 'SECURE_AUTH_KEY', '${secureAuthKey}' );
define( 'LOGGED_IN_KEY', '${loggedInKey}' );
define( 'NONCE_KEY', '${nonceKey}' );
define( 'AUTH_SALT', '${authSalt}' );
define( 'SECURE_AUTH_SALT', '${secureAuthSalt}' );
define( 'LOGGED_IN_SALT', '${loggedInSalt}' );
define( 'NONCE_SALT', '${nonceSalt}' );
// Headless auth endpoints return 503 without this, so auth specs would fail.
define( 'BLUEWORX_LABS_JWT_SECRET', '${JWT_SECRET}' );
$table_prefix = 'wp_';
// Debug ON, but never rendered into the response. The SQLite drop-in emits
// harmless notices on large transients, and HTML error output injected into a
// REST body makes JSON.parse fail — which reads as a broken endpoint rather
// than a warning. Errors go to wp-content/debug.log instead.
define( 'WP_DEBUG', true );
define( 'WP_DEBUG_DISPLAY', false );
define( 'WP_DEBUG_LOG', true );
@ini_set( 'display_errors', '0' );
define( 'WP_HOME', '${baseUrl}' );
define( 'WP_SITEURL', '${baseUrl}' );
if ( ! defined( 'ABSPATH' ) ) { define( 'ABSPATH', __DIR__ . '/' ); }
require_once ABSPATH . 'wp-settings.php';
`);
}

// Link rather than copy so edits in the repo take effect immediately. Windows
// junctions need no admin rights; elsewhere a symlink does the job.
function linkPlugin(pluginDir, slug) {
  const dest = join(wpDir, 'wp-content', 'plugins', slug);
  if (existsSync(dest)) return;
  try {
    if (platform() === 'win32') {
      execFileSync('cmd', ['/c', 'mklink', '/J', dest, pluginDir], { stdio: 'ignore' });
    } else {
      execFileSync('ln', ['-s', pluginDir, dest], { stdio: 'ignore' });
    }
  } catch {
    log('Link failed — copying the plugin instead (edits will NOT be live).');
    cpSync(pluginDir, dest, { recursive: true });
  }
}

async function installWordPress() {
  const res = await fetch(`${baseUrl}/wp-admin/install.php?step=2`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({
      weblog_title: 'Plugin Test Site',
      user_name: ADMIN_USER,
      admin_password: ADMIN_PASS,
      admin_password2: ADMIN_PASS,
      pw_weak: '1',
      admin_email: ADMIN_EMAIL,
      blog_public: '0',
      Submit: 'Install WordPress',
    }),
  });
  const body = await res.text();
  if (/already installed/i.test(body)) {
    log('WordPress already installed — reusing.');
    return;
  }
  if (!/success|has been installed/i.test(body)) {
    fail('WordPress install did not report success. Check the server log.');
  }
  log('WordPress installed.');
}

// Pretty permalinks are required or /wp-json/ returns HTML and every REST spec
// fails on "Unexpected token '<'".
function bootstrapScript(slug) {
  return `<?php
require_once __DIR__ . '/wp-load.php';
require_once ABSPATH . 'wp-admin/includes/plugin.php';
require_once ABSPATH . 'wp-includes/rewrite.php';
global $wp_rewrite;
if ( get_option( 'permalink_structure' ) !== '/%postname%/' ) {
  $wp_rewrite->set_permalink_structure( '/%postname%/' );
  $wp_rewrite->flush_rules( true );
}
$main = '${slug}/${slug}.php';
if ( ! file_exists( WP_PLUGIN_DIR . '/' . $main ) ) {
  foreach ( glob( WP_PLUGIN_DIR . '/${slug}/*.php' ) as $candidate ) {
    if ( preg_match( '/^\\s*\\*?\\s*Plugin Name:/im', file_get_contents( $candidate ) ) ) {
      $main = '${slug}/' . basename( $candidate );
      break;
    }
  }
}
$res = activate_plugin( $main, '', false, false );
echo is_wp_error( $res ) ? 'ACTIVATION_ERROR: ' . $res->get_error_message() : 'PLUGIN_ACTIVE: ' . $main;
echo "\\n" . 'PERMALINKS: ' . get_option( 'permalink_structure' ) . "\\n";
`;
}

function runPhp(source) {
  const file = join(wpDir, 'wp-test-env-bootstrap.php');
  writeFileSync(file, source);
  try {
    const out = execFileSync('php', [file], { encoding: 'utf8', cwd: wpDir });
    if (out.includes('ACTIVATION_ERROR')) fail(out.trim());
    out.trim().split('\n').forEach((line) => log(line));
  } finally {
    rmSync(file, { force: true });
  }
}

// --- server -----------------------------------------------------------------

function startServer() {
  const logPath = join(dir, 'php-server.log');
  const child = spawn('php', ['-S', `127.0.0.1:${port}`, '-t', wpDir], {
    cwd: wpDir,
    detached: true,
    stdio: ['ignore', openLog(logPath), openLog(logPath)],
  });
  child.unref();
  writeFileSync(pidFile, String(child.pid));
  log(`PHP server started on ${baseUrl} (pid ${child.pid}, log: ${logPath})`);
}

function openLog(path) {
  return openSync(path, 'a');
}

async function waitForServer() {
  for (let i = 0; i < 30; i += 1) {
    try {
      const res = await fetch(baseUrl, { redirect: 'manual' });
      if (res.status) return;
    } catch {
      await sleep(1000);
    }
  }
  fail(`PHP server did not come up on ${baseUrl}. See ${join(dir, 'php-server.log')}.`);
}

function stopServer({ quiet = false } = {}) {
  if (!existsSync(pidFile)) {
    if (!quiet) log('No server pid file — nothing to stop.');
    return;
  }
  const pid = Number(readFileSync(pidFile, 'utf8').trim());
  try {
    if (platform() === 'win32') {
      execFileSync('taskkill', ['/PID', String(pid), '/T', '/F'], { stdio: 'ignore' });
    } else {
      process.kill(pid, 'SIGTERM');
    }
    if (!quiet) log(`Stopped server (pid ${pid}).`);
  } catch {
    if (!quiet) log(`Server pid ${pid} was not running.`);
  }
  rmSync(pidFile, { force: true });
}

// --- helpers ----------------------------------------------------------------

function requirePhp() {
  let version;
  try {
    version = execFileSync('php', ['-r', 'echo PHP_VERSION;'], { encoding: 'utf8' }).trim();
  } catch {
    fail('PHP was not found on PATH. This harness runs WordPress on your own PHP.');
  }
  const mods = execFileSync('php', ['-m'], { encoding: 'utf8' });
  if (!/^pdo_sqlite$/im.test(mods)) {
    fail(`PHP ${version} has no pdo_sqlite extension. The SQLite drop-in needs it — enable it in php.ini.`);
  }
  log(`Using PHP ${version} (pdo_sqlite present).`);
}

async function download(url, dest) {
  const res = await fetch(url, { redirect: 'follow' });
  if (!res.ok) fail(`Download failed (${res.status}): ${url}`);
  writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
}

// Node ships no zip reader. bsdtar handles zip on every platform; on Windows it
// must be the System32 one, because GNU tar in Git Bash cannot read zip.
function unzip(zipPath, destDir) {
  const tar = platform() === 'win32' ? `${process.env.WINDIR}\\System32\\tar.exe` : 'tar';
  try {
    execFileSync(tar, ['-xf', zipPath, '-C', destDir], { stdio: 'ignore' });
  } catch {
    try {
      execFileSync('unzip', ['-q', '-o', zipPath, '-d', destDir], { stdio: 'ignore' });
    } catch {
      fail(`Could not extract ${zipPath}. Need bsdtar or unzip available.`);
    }
  }
  rmSync(zipPath, { force: true });
}

function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const key = a.slice(2);
      const next = argv[i + 1];
      if (next && !next.startsWith('--')) { out[key] = next; i += 1; } else { out[key] = true; }
    } else {
      out._.push(a);
    }
  }
  return out;
}

// Declarations, not const arrows: this file awaits at the top level, so these
// must be hoisted or the first call hits the temporal dead zone.
function sleep(ms) {
  return new Promise((r) => { setTimeout(r, ms); });
}

function log(msg) {
  console.log(msg);
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
